#!/usr/bin/env node
// Copies the RVP test's content from where Philosopher writes it (the personal workspace's Obsidian vault,
// knowledge/philosophy/rvp-test/) into this repo: questions.json → src/rvp/bank.json, and content/*.json merged into
// src/rvp/content.json. Run locally after Philosopher's edits, then commit; CI builds from the committed copies.
// Usage: node scripts/rvp-sync.mjs [path to rvp-test]   (default ~/dev/personal/knowledge/philosophy/rvp-test)
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";

const SRC = process.argv[2] || join(homedir(), "dev/personal/knowledge/philosophy/rvp-test");
if (!existsSync(SRC)) { console.error(`rvp-sync: ${SRC} not found`); process.exit(1); }
const read = (f) => JSON.parse(readFileSync(join(SRC, f), "utf8"));
const out = (f, v) => writeFileSync(new URL(`../src/rvp/${f}`, import.meta.url), JSON.stringify(v, null, 2) + "\n");

out("bank.json", read("questions.json"));
const dir = join(SRC, "content");
const archetypes = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".json") && !["facets.json", "differences.json", "names-es.json"].includes(f)).sort()) {
  const a = JSON.parse(readFileSync(join(dir, f), "utf8"));
  if (a.slug !== f.replace(/\.json$/, "")) { console.error(`rvp-sync: ${f} has slug ${a.slug}`); process.exit(1); }
  archetypes[a.slug] = a;
}
out("content.json", {
  note: "Generated by scripts/rvp-sync.mjs from knowledge/philosophy/rvp-test/content (Philosopher's). Edit there, not here.",
  facets: read("content/facets.json"), differences: read("content/differences.json"), archetypes,
});
// Spanish archetype names (content/names-es.json, Philosopher's; neutral where Spanish allows) go into archetypes.json.
const namesFile = join(dir, "names-es.json");
if (existsSync(namesFile)) {
  const names = JSON.parse(readFileSync(namesFile, "utf8"));
  const file = new URL("../src/rvp/archetypes.json", import.meta.url), doc = JSON.parse(readFileSync(file, "utf8"));
  for (const a of doc.archetypes) {
    const es = names[a.slug]?.es?.trim();
    if (!es) { console.error(`rvp-sync: names-es.json has no name for ${a.slug}`); process.exit(1); }
    a.name.es = es;
  }
  writeFileSync(file, JSON.stringify(doc, null, 1) + "\n");
}
console.log(`rvp-sync: bank ${read("questions.json").version}, ${Object.keys(archetypes).length} archetype file(s)`);
