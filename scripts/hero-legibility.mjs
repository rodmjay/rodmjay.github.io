// The living hero's legibility check (Rod 11/27 via Designer: "the only point is to make the name visible no matter the
// background"; design/specs/rodmjay-home.md). For each measured width it maps the name-and-title box (plus 12 px top and
// sides, 8 px below) onto the picture with the page's own cover-fit math, takes the brightest 2 % of pixels (relative
// luminance) and adds 0.03 headroom for the ripples. White text clears 4.5:1 when the background is at or under 0.183:
// then no scrim; otherwise a scrim of alpha 1 - (0.183/L)^(1/2.2), rounded up to 0.05, capped at 0.6.
// Usage: node scripts/hero-legibility.mjs <descriptor.json> [--write]. Without --write it checks that the descriptor's
// stored result matches the picture as it is now, and fails (CI) when a plate changed without a new measurement or a
// breakpoint can't be made legible within the cap.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const file = process.argv[2], write = process.argv.includes("--write");
const d = JSON.parse(readFileSync(file, "utf8"));
const lin = (c) => { c /= 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
const bp = (w) => (w < 600 ? "phone" : w < 840 ? "tablet" : "desktop");
const cache = new Map();
async function pixels(src) {
  if (!cache.has(src)) cache.set(src, await sharp(join(process.cwd(), "public", src)).removeAlpha().raw().toBuffer({ resolveWithObject: true }));
  return cache.get(src);
}
const result = {}, problems = [], perWidth = [];
for (const s of d.legibility.samples) {
  const v = d.variants.find((x) => x.breakpoint === bp(s.w));
  if (!v) { problems.push(`no variant for ${s.w}px`); continue; }
  const { data, info } = await pixels(v.image);
  const [fx, fy] = v.focus.split(" ").map((p) => parseFloat(p) / 100);
  const sc = Math.max(s.cw / info.width, s.ch / info.height), ox = (s.cw - info.width * sc) * fx, oy = (s.ch - info.height * sc) * fy;
  const [x0, y0, x1, y1] = s.box, lum = [];
  for (let y = Math.max(0, y0); y < Math.min(s.ch, y1); y++) for (let x = Math.max(0, x0); x < Math.min(s.cw, x1); x++) {
    const ix = Math.floor((x - ox) / sc), iy = Math.floor((y - oy) / sc);
    if (ix < 0 || iy < 0 || ix >= info.width || iy >= info.height) continue;
    const i = (iy * info.width + ix) * 3;
    lum.push(0.2126 * lin(data[i]) + 0.7152 * lin(data[i + 1]) + 0.0722 * lin(data[i + 2]));
  }
  lum.sort((a, b) => a - b);
  const L = (lum.length ? lum[Math.floor(lum.length * 0.98)] : 0) + 0.03;
  let a = L <= 0.183 ? 0 : Math.ceil((1 - (0.183 / L) ** (1 / 2.2)) * 20) / 20;
  if (a > 0.6) problems.push(`${s.w}px needs a scrim of ${a.toFixed(2)}, over the 0.6 cap: the picture is too bright behind the name`);
  if (process.env.VERBOSE) console.log(`${s.w}px: L ${L.toFixed(3)} scrim ${a}`);
  perWidth.push({ w: s.w, a: Math.min(a, 0.6) });
  const k = bp(s.w), prev = result[k];
  if (!prev || a > prev.scrimAlpha || (a === prev.scrimAlpha && L > prev.lmax)) result[k] = { scrimAlpha: Math.min(a, 0.6), lmax: +L.toFixed(3), worstWidth: s.w };
}
const fingerprint = (await Promise.all(d.variants.map(async (v) => { const m = await sharp(join(process.cwd(), "public", v.image)).stats(); return m.channels.map((c) => c.mean.toFixed(2)).join(","); }))).join("|");
console.log(Object.entries(result).map(([k, r]) => `${k}: L ${r.lmax} (worst at ${r.worstWidth}px) -> scrim ${r.scrimAlpha}`).join("\n"));
// The scrim per width range: each range takes the larger of its two measured ends (within one layout), so it is never lighter than the
// picture needs and never darker than its own ends require.
perWidth.sort((x, y) => x.w - y.w);
// A range never borrows across a layout breakpoint (600, 840): the next sample there is a different layout.
const ranges = perWidth.map((p, i) => { const n = perWidth[i + 1], same = n && bp(n.w) === bp(p.w);
  return { min: i === 0 ? 0 : p.w, max: n ? n.w - 0.02 : null, alpha: Math.max(p.a, same ? n.a : 0) }; });
const css = `/* Generated by scripts/hero-legibility.mjs from ${file} (do not edit): the scrim behind the home's name and title, only
   where the picture is too bright for white text at 4.5:1 (Rod 11/27, design/specs/rodmjay-home.md). */
` + ranges.filter((r) => r.alpha > 0).map((r) => `@media (min-width: ${r.min}px)${r.max ? ` and (max-width: ${r.max}px)` : ""} { .stage-text { --scrim: ${r.alpha}; } }`).join("\n") + "\n";
if (write) {
  d.legibility.result = result; d.legibility.ranges = ranges; d.legibility.fingerprint = fingerprint;
  writeFileSync(file, JSON.stringify(d, null, 2) + "\n");
  writeFileSync(join(process.cwd(), "public/hero-legibility.css"), css);
  console.log(`hero-legibility: wrote ${file}`);
} else {
  if (d.legibility.fingerprint !== fingerprint) problems.push("a hero picture changed since the last measurement: run node scripts/hero-legibility.mjs <descriptor> --write and commit");
  for (const [k, r] of Object.entries(result)) if (d.legibility.result?.[k]?.scrimAlpha !== r.scrimAlpha) problems.push(`${k}: stored scrim ${d.legibility.result?.[k]?.scrimAlpha} but the picture needs ${r.scrimAlpha}`);
  if (readFileSync(join(process.cwd(), "public/hero-legibility.css"), "utf8") !== css) problems.push("public/hero-legibility.css is out of date: run with --write");
}
if (problems.length) { console.error(`hero-legibility:\n  ${problems.join("\n  ")}`); process.exit(1); }
